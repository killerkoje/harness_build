create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  root_path text not null unique,
  name text not null,
  description text not null default '',
  dev_url text
);

create table if not exists public.plans (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  title text not null,
  sections jsonb not null,
  status text not null default 'draft',
  notion_epic_page_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.plan_snapshots (
  id bigint generated by default as identity primary key,
  plan_id bigint not null references public.plans(id) on delete cascade,
  label text not null,
  content jsonb not null,
  created_at timestamptz not null default now()
);

create table if not exists public.issues (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  number integer not null,
  plan_id bigint references public.plans(id) on delete set null,
  title text not null,
  priority text not null,
  description text not null,
  status text not null default 'planned',
  notion_page_id text,
  notion_status text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (project_id, number)
);

create table if not exists public.wireframes (
  id bigint generated by default as identity primary key,
  issue_id bigint not null unique references public.issues(id) on delete cascade,
  screens jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.issue_subtasks (
  id bigint generated by default as identity primary key,
  issue_id bigint not null references public.issues(id) on delete cascade,
  title text not null,
  done boolean not null default false,
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.design_systems (
  id bigint generated by default as identity primary key,
  project_id bigint not null unique references public.projects(id) on delete cascade,
  name text not null,
  version text not null,
  package_name text not null,
  storybook_path text not null,
  tokens jsonb not null,
  components jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

